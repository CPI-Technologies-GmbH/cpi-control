const colorMap: Record<string, string> = {
  github: 'text-white',
  vercel: 'text-white',
  kubernetes: 'text-[#326CE5]',
  digitalocean: 'text-[#0080FF]',
  slack: 'text-[#E01E5A]',
  openai: 'text-white',
  bitbucket: 'text-[#2684FF]',
  semaphore: 'text-[#53B94E]',
};

export function ProviderLogo({ provider, size = 20 }: { provider: string; size?: number }) {
  const Logo = logoMap[provider];
  const color = colorMap[provider] || 'text-gray-400';

  if (!Logo) {
    return (
      <div
        className="flex items-center justify-center rounded-lg bg-gray-700 text-gray-300 text-xs font-bold uppercase"
        style={{ width: size + 8, height: size + 8 }}
      >
        {provider.slice(0, 2)}
      </div>
    );
  }

  return (
    <div className={`${color} flex items-center justify-center`}>
      <Logo size={size} />
    </div>
  );
}
