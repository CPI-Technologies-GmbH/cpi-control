/**
 * Generic provider color map used to pick the right color class for each icon.
 */
const providerColorClass: Record<string, string> = {
  vercel: 'text-white',
  github: 'text-white',
  github_actions: 'text-white',
  // Kubernetes, DigitalOcean, Semaphore have built-in colors in the SVG
  aws: 'text-[#FF9900]',
  docker: 'text-[#2496ED]',
};

/**
 * Unified ProviderIcon component.
 * Maps a provider string to the correct official SVG icon.
 */
export function ProviderIcon({
  provider,
  size = 16,
  className,
}: {
  provider: string;
  size?: number;
  className?: string;
}) {
  const colorClass = providerColorClass[provider];
  const mergedClass = [colorClass, className].filter(Boolean).join(' ');

  switch (provider) {
    case 'kubernetes':
      return <KubernetesIcon size={size} className={className} />;
    case 'vercel':
      return <VercelIcon size={size} className={mergedClass} />;
    case 'github':
    case 'github_actions':
      return <GitHubIcon size={size} className={mergedClass} />;
    case 'semaphore':
      return <SemaphoreIcon size={size} className={className} />;
    case 'digitalocean':
      return <DigitalOceanIcon size={size} className={className} />;
    case 'aws':
      return <AWSIcon size={size} className={mergedClass} />;
    case 'docker':
      return <DockerIcon size={size} className={mergedClass} />;
    default:
      return <Cloud size={size} className={className || 'text-gray-400'} />;
  }
}
